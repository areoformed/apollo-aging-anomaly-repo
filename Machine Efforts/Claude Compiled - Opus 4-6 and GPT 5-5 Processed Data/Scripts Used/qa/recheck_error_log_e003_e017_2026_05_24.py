#!/usr/bin/env python3
"""Recheck DATA-INTEGRITY-ERROR-LOG items E003-E017 against current files."""

from __future__ import annotations

import csv
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
FINAL = ROOT / "Final - Analysis - Enriched Datasets"
DATA = ROOT / "data"
OUT = DATA / "error-log-E003-E017-recheck-2026-05-24.tsv"


def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def line_for_name(path: Path, name: str) -> int | None:
    for lineno, line in enumerate(path.read_text().splitlines(), start=1):
        if line.startswith(name + "\t"):
            return lineno
    return None


def enriched_files() -> list[Path]:
    return [
        FINAL / "03E-non-apollo-enriched.tsv",
        FINAL / "07E-lunar-enriched.tsv",
        FINAL / "08E-non-lunar-apollo-enriched.tsv",
        FINAL / "09-x15-pilots-enriched.tsv",
        FINAL / "10-dyna-soar-pilots-enriched.tsv",
        FINAL / "11-mol-full-enriched.tsv",
    ]


def sg_counts(path: Path) -> tuple[int, int, int, int]:
    rows = read_tsv(path)
    sg_y = sum(r.get("Space Grandpa") == "Y" for r in rows)
    age80 = [
        r
        for r in rows
        if r.get("Current Age or Age at Death")
        and float(r["Current Age or Age at Death"]) >= 80
    ]
    sg80 = sum(r.get("Space Grandpa") == "Y" for r in age80)
    return len(rows), sg_y, len(age80), sg80


def add(rows: list[dict[str, str]], issue: str, status: str, current_state: str, evidence: str) -> None:
    rows.append(
        {
            "issue": issue,
            "status": status,
            "current_state": current_state,
            "evidence": evidence,
        }
    )


def main() -> None:
    rows: list[dict[str, str]] = []

    qafix = ROOT / "Scripts Used/qa/qa_fix_enriched_tsvs.py"
    mayfix = ROOT / "Scripts Used/qa/may19-qa-fixes.py"
    clear_patterns = []
    for p in (qafix, mayfix):
        text = p.read_text()
        clear_patterns.append("fields[16] = ''" in text and "fields[15] == 'N'" in text)
    apollo8 = FINAL / "08E-non-lunar-apollo-enriched.tsv"
    apollo8_rows = {r["Name"]: r for r in read_tsv(apollo8)}
    affected = ["Walter Marty Schirra Jr.", "James Alton McDivitt Jr."]
    blank_affected = [
        name
        for name in affected
        if apollo8_rows[name]["Space Grandpa"] == "N"
        and apollo8_rows[name]["Space Grandpa Citation"] == ""
    ]
    add(
        rows,
        "E003",
        "resolved" if not blank_affected and not any(clear_patterns) else "open",
        f"{len(blank_affected)}/2 affected 08E rows still have SG=N with blank citation; citation-clearing logic present in {sum(clear_patterns)}/2 QA scripts.",
        "; ".join(
            f"{name} line {line_for_name(apollo8, name)}" for name in blank_affected
        )
        + f"; scripts_clear={all(clear_patterns)}",
    )

    sg_n_total = sg_n_blank = 0
    populated_notes: list[str] = []
    for p in enriched_files():
        for r in read_tsv(p):
            if r.get("Space Grandpa") != "N":
                continue
            sg_n_total += 1
            if r.get("Space Grandpa Citation", ""):
                populated_notes.append(f"{p.name}:{line_for_name(p, r['Name'])}:{r['Name']}")
            else:
                sg_n_blank += 1
    add(
        rows,
        "E004",
        "resolved" if sg_n_blank == 0 else "open",
        f"{sg_n_total} SG=N rows: {sg_n_blank} blank citations, {len(populated_notes)} populated citation/rationale cells.",
        "; ".join(populated_notes[:12]) + ("; ..." if len(populated_notes) > 12 else ""),
    )

    wider_parts = []
    for fname in [
        "09-x15-pilots-enriched.tsv",
        "10-dyna-soar-pilots-enriched.tsv",
        "11-mol-full-enriched.tsv",
    ]:
        count, sg_y, age80, sg80 = sg_counts(FINAL / fname)
        wider_parts.append(f"{fname}: rows={count}, SG={sg_y}, age80={age80}, SG80={sg80}")
    adams = next(
        r
        for r in read_tsv(FINAL / "09-x15-pilots-enriched.tsv")
        if r["Name"] == "Michael James Adams"
    )
    add(
        rows,
        "E005",
        "resolved" if all(s in (ROOT / "BUILD-LOG.md").read_text() for s in ["2/13", "1/4", "2/8", "0/8 `Went to Space=Y`"]) else "open",
        "BUILD-LOG wider-cohort sections distinguish historical full rosters from current deduplicated final TSV counts.",
        "; ".join(wider_parts) + f"; Michael Adams Went to Space={adams['Went to Space']}",
    )

    manual_checks = [
        (ROOT / "Scripts Used/mid-period-extraction-log.md", "manual, not scripted"),
        (ROOT / "Scripts Used/extraction-log.md", "hand-constructed data"),
        (ROOT / "Scripts Used/extraction-log.md", "not generated by a script"),
    ]
    present = sum(needle in path.read_text() for path, needle in manual_checks)
    add(
        rows,
        "E006",
        "partially_resolved" if (DATA / "enriched-row-provenance-2026-05-24.tsv").exists() else "open",
        "Manual/non-scripted enrichment evidence remains, but row-level provenance output now exists.",
        f"{present}/{len(manual_checks)} manual-pipeline phrases found; provenance_file_exists={(DATA / 'enriched-row-provenance-2026-05-24.tsv').exists()}",
    )

    root_files = [ROOT / p.name for p in enriched_files()]
    missing_root = sum(not p.exists() for p in root_files)
    stale_refs = []
    for p in [
        ROOT / "Scripts Used/enrichment/update_mort_fields.py",
        ROOT / "Scripts Used/enrichment/upgrade_space_grandpas.py",
        ROOT / "Scripts Used/qa/sg_denominator_breakdown.py",
        ROOT / "Scripts Used/qa/lunar_median_ages.py",
        ROOT / "Scripts Used/military-programs/dedup_military_files.py",
    ]:
        text = p.read_text()
        if re.search(r"open\(['\"](?:03E|07E|08E|09-x15|10-dyna|11-mol)[^'\"]+\.tsv['\"]", text):
            stale_refs.append(str(p.relative_to(ROOT)))
    add(
        rows,
        "E007",
        "resolved" if not stale_refs else "open",
        f"{missing_root}/{len(root_files)} root-level enriched TSVs missing by design; stale bare open() path references in cited scripts={len(stale_refs)}.",
        "; ".join(stale_refs),
    )

    missing_dates = 0
    for p in [DATA / f"{i:02d}-{name}.tsv" for i, name in [
        (1, "all-pre-1970-astronauts"),
        (2, "deduplicated-pre-1970"),
        (3, "non-apollo-astronauts"),
        (4, "non-apollo-flew"),
        (5, "non-apollo-never-flew"),
    ]]:
        for r in read_tsv(p):
            missing_dates += (r.get("Date of Birth") == "") + (r.get("Date of Selection") == "")
    add(rows, "E008", "resolved" if missing_dates == 0 else "open", f"{missing_dates} blank DOB/selection-date cells remain across data/01-05.", "raw/reference TSV date columns")

    partial_counts = {}
    for p in [
        DATA / "06-apollo-applications.tsv",
        DATA / "07-lunar-astronauts.tsv",
        DATA / "08-non-lunar-apollo.tsv",
    ]:
        partial_counts[p.name] = sum(
            bool(re.fullmatch(r"\d{4}-\d{2}", r.get("Date of Selection", "")))
            for r in read_tsv(p)
        )
    add(
        rows,
        "E009",
        "resolved" if sum(partial_counts.values()) == 0 else "open",
        "Month-only Date of Selection value counts.",
        "; ".join(f"{k}={v}" for k, v in partial_counts.items()),
    )

    placeholder_count = 0
    for p in [
        DATA / "01-all-pre-1970-astronauts.tsv",
        DATA / "02-deduplicated-pre-1970.tsv",
        DATA / "03-non-apollo-astronauts.tsv",
        DATA / "04-non-apollo-flew.tsv",
        DATA / "05-non-apollo-never-flew.tsv",
    ]:
        placeholder_count += sum(r.get("Astronaut Group") == "Group " for r in read_tsv(p))
    add(rows, "E010", "resolved" if placeholder_count == 0 else "open", f"{placeholder_count} literal `Group ` placeholders remain across data/01-05.", "raw/reference TSV Astronaut Group columns")

    raw03 = {r["Name"]: r for r in read_tsv(DATA / "03-non-apollo-astronauts.tsv")}
    enriched03 = {r["Name"]: r for r in read_tsv(FINAL / "03E-non-apollo-enriched.tsv")}
    e011_examples = [
        ("Joseph Percival Allen IV", "Joseph Percival Allen IV"),
        ("John Sumter Bull", "John Sumter Bull"),
        ("Edward Galen Givens Jr.", "Edward Galen Givens Jr."),
    ]
    e011_notes = []
    e011_mismatches = 0
    for raw_name, final_name in e011_examples:
        if raw03[raw_name]["Missions Flown"] != enriched03[final_name]["Missions Flown"]:
            e011_mismatches += 1
        e011_notes.append(
            f"{raw_name}: raw={raw03[raw_name]['Missions Flown']} / final={enriched03[final_name]['Missions Flown']}"
        )
    add(
        rows,
        "E011",
        "resolved" if e011_mismatches == 0 else "partially_resolved",
        "Checked raw Missions Flown examples now match final actual-flown mission values.",
        "; ".join(e011_notes),
    )

    headers_with_ids = []
    for p in [
        DATA / "03-non-apollo-astronauts.tsv",
        FINAL / "03E-non-apollo-enriched.tsv",
        DATA / "07-lunar-astronauts.tsv",
        FINAL / "07E-lunar-enriched.tsv",
        DATA / "08-non-lunar-apollo.tsv",
        FINAL / "08E-non-lunar-apollo-enriched.tsv",
    ]:
        header = p.read_text().splitlines()[0].split("\t")
        headers_with_ids.append(any(h.lower() in {"person_id", "person id", "aliases", "alias"} for h in header))
    add(
        rows,
        "E012",
        "resolved" if (DATA / "person-id-alias-map-2026-05-24.tsv").exists() else "open",
        "Raw/enriched display-name variants remain, but a stable person-id/alias mapping table now exists.",
        f"headers_with_person_id_or_alias={sum(headers_with_ids)}/{len(headers_with_ids)}; alias_map_exists={(DATA / 'person-id-alias-map-2026-05-24.tsv').exists()}",
    )

    sg_audit = read_tsv(DATA / "SG-audit-existing-sources.tsv")
    living_count = sum(r.get("Death Date") == "Living" for r in sg_audit)
    add(rows, "E013", "resolved" if living_count == 0 and "Status" in sg_audit[0] else "open", f"{living_count} Death Date cells still contain sentinel `Living`.", "data/SG-audit-existing-sources.tsv")

    ssa_lines = (DATA / "ssa-1930-male-cohort-lifetable.tsv").read_text().splitlines()
    add(
        rows,
        "E014",
        "resolved" if ssa_lines and ssa_lines[0] == "age\tqx\tlx\tdx" else "open",
        "SSA life table now starts with the TSV header; metadata lives in a sidecar markdown file.",
        f"line1={ssa_lines[0]!r}; metadata_exists={(DATA / 'ssa-1930-male-cohort-lifetable-metadata.md').exists()}",
    )

    mort_note_headers = 0
    mort_patterns = [
        "Brief illness",
        "Not specified",
        "Not publicly disclosed",
        "Natural causes",
        "Cause not specified",
        "unknown",
        "Ongoing health issues",
    ]
    mort_hits = []
    for p in enriched_files():
        header = p.read_text().splitlines()[0].split("\t")
        if "Mort / cause note" in header:
            mort_note_headers += 1
        for r in read_tsv(p):
            mort = r.get("Mort / cause note", r.get("Mort", ""))
            if any(pat in mort for pat in mort_patterns):
                mort_hits.append(f"{p.name}:{line_for_name(p, r['Name'])}:{r['Name']}={mort}")
    add(rows, "E015", "resolved" if mort_note_headers == len(enriched_files()) else "open", f"{len(mort_hits)} placeholder/non-specific cause-note values remain under renamed `Mort / cause note` field.", f"renamed_headers={mort_note_headers}/{len(enriched_files())}; " + ("; ".join(mort_hits[:8]) + ("; ..." if len(mort_hits) > 8 else "")))

    unknown_time = []
    for p in enriched_files():
        for r in read_tsv(p):
            if r.get("Time in Space", "").lower() == "unknown":
                unknown_time.append(f"{p.name}:{line_for_name(p, r['Name'])}:{r['Name']}")
    add(rows, "E016", "resolved" if not unknown_time else "open", f"{len(unknown_time)} Time in Space value remains `unknown`.", "; ".join(unknown_time))

    core_counts = []
    for fname in ["07E-lunar-enriched.tsv", "08E-non-lunar-apollo-enriched.tsv", "03E-non-apollo-enriched.tsv"]:
        count, sg_y, _, _ = sg_counts(FINAL / fname)
        core_counts.append(f"{fname}: {sg_y}/{count}")
    std_files = [
        FINAL / "Standardized Searches/SG-standardized-searches-lunar.tsv",
        FINAL / "Standardized Searches/SG-standardized-searches-control.tsv",
    ]
    std_rows = [r for p in std_files for r in read_tsv(p)]
    conflicts = [r["Name"] for r in std_rows if r["Current SG"] != r["Recommended SG"]]
    std_y = sum(r["Recommended SG"] == "Y" for r in std_rows)
    add(
        rows,
        "E017",
        "partially_resolved" if len(conflicts) == 1 and conflicts == ["Curt Michel"] else ("resolved" if not conflicts else "open"),
        "BUILD-LOG core counts updated to current final TSVs; only the low-confidence Curt Michel standardized-search downgrade remains unadjudicated.",
        "; ".join(core_counts) + f"; standardized_conflicts={len(conflicts)}; standardized_recommended_Y={std_y}/{len(std_rows)}",
    )

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["issue", "status", "current_state", "evidence"], delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
